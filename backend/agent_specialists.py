def validate_drafts(raw, sources):
    values = raw.get('reply_drafts', [])
    if not isinstance(values, list):
        raise ValueError('답장 초안의 형식을 읽을 수 없습니다.')
    source_map = {s['id']: s for s in sources}
    drafts, warnings = [], []
    for value in values[:12]:
        if not isinstance(value, dict) or not isinstance(value.get('body'), str) or not value['body'].strip():
            continue
        identity = value.get('evidence_id')
        source = source_map.get(identity) if isinstance(identity, str) else None
        quote = value.get('evidence_quote') if isinstance(value.get('evidence_quote'), str) else ''
        grounded = bool(source and quote and quote in source['excerpt'])
        recipient = str(value.get('recipient') or '')[:250].replace('\r', '').replace('\n', '')
        address = parseaddr(recipient)[1]
        addresses = set(re.findall(r"[A-Za-z0-9.!#$%&'*+/=?^_`{|}~-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+", source['excerpt'])) if source else set()
        # A draft may be copied even without an addressee, but never silently
        # preaddress it to a model-invented or injected mailbox.
        if not grounded or not address or address not in addresses or not re.fullmatch(r'[^\s<>@]+@[^\s<>@]+\.[^\s<>@]+', address):
            recipient = ''
        else:
            recipient = address
        subject = value.get('subject') if isinstance(value.get('subject'), str) else '답장 초안'
        drafts.append({'subject': subject.replace('\r', ' ').replace('\n', ' ')[:200],
                       'recipient': recipient, 'body': value['body'].strip()[:6000],
                       'evidence_id': identity if grounded else None, 'evidence_quote': quote[:6000] if grounded else '',
                       'evidence_verified': grounded})
        if not grounded:
            warnings.append('답장 초안의 인용을 원문에서 확인하지 못했습니다. 받는 사람을 비웠습니다.')
    return drafts, warnings


def plan_focus(run):
    settings = run['focus']
    day = date.fromisoformat(settings['date'])
    start = datetime.combine(day, time.fromisoformat(settings['start']), KST)
    end = datetime.combine(day, time.fromisoformat(settings['end']), KST)
    captured = _stamp(run['created_at'])
    if captured > start:
        start = captured.replace(second=0, microsecond=0) + timedelta(minutes=1)
    events = [s for s in run['sources'] if s.get('source_type') == 'event']
    busy, warnings = [], []
    if run.get('metrics', {}).get('calendar_sources_omitted'):
        warnings.append('자료 길이·개수 제한 때문에 선택 범위의 일정 일부를 포함하지 못했습니다. 참고 자료를 줄이거나 일정을 직접 선택한 뒤 다시 실행하세요.')
    for source in events:
        meta = source.get('source_metadata', {})
        if str(meta.get('status', '')).lower() in ('cancelled', 'canceled') or str(meta.get('show_as', '')).lower() == 'free':
            continue
        if meta.get('recurrence_unexpanded') or meta.get('time_uncertain'):
            warnings.append(f"{source['title']}: 반복 일정 또는 시간대를 확인해야 집중 시간을 계산할 수 있습니다.")
            continue
        left, right = _stamp(meta.get('start_at')), _stamp(meta.get('end_at'))
        if not left or not right or right <= left:
            warnings.append(f"{source['title']}: 일정의 시작·종료 시각을 확인해 주세요.")
            continue
        if left < end and right > start:
            busy.append((max(start, left), min(end, right)))
    plan = {**settings, 'time_zone': 'Asia/Seoul', 'busy_count': len(busy), 'calendar_sources': len(events),
            'coverage_note': '선택해 가져온 일정 사본만 반영합니다. 선택하지 않은 일정이나 이후 변경 사항은 포함하지 않습니다.',
            'warnings': warnings, 'unscheduled_count': run.get('metrics', {}).get('open', 0)}
    if warnings:
        return [], plan
    free, cursor = [], start
    for left, right in sorted(busy):
        if left > cursor:
            free.append((cursor, left))
        cursor = max(cursor, right)
    if cursor < end:
        free.append((cursor, end))
    tasks = [s for s in run['sources'] if s['type'] == 'task' and s.get('data', {}).get('status') != 'completed']
    if not tasks and run.get('metrics', {}).get('open', 0):
        plan['warnings'].append('자료 길이 제한 때문에 미완료 업무의 상세 기록을 포함하지 못했습니다. 참고 자료를 줄인 뒤 다시 실행하세요.')
        return [], plan
    tasks.sort(key=lambda s: (s['data'].get('priority') != 'high', s['data'].get('due_at') or '9999', s['id']))
    candidates = tasks[:12] or [next(s for s in run['sources'] if s['id'] == 'request')]
    blocks, position = [], 0
    duration, pause = timedelta(minutes=settings['block_minutes']), timedelta(minutes=settings['break_minutes'])
    for left, right in free:
        # Preserve availability at sub-minute boundaries while publishing
        # minute-precision blocks: round up, never back into a busy event.
        cursor = left.replace(second=0, microsecond=0)
        if cursor < left:
            cursor += timedelta(minutes=1)
        while cursor + duration <= right and position < len(candidates) and len(blocks) < 12:
            source = candidates[position]
            title = source['title'] if source['type'] == 'task' else '집중 업무'
            blocks.append({'title': title, 'start': cursor.isoformat(timespec='minutes'),
                'end': (cursor + duration).isoformat(timespec='minutes'), 'task_id': source.get('task_id'),
                'reason': '선택한 일정과 겹치지 않는 시간에 배치한 제안입니다.',
                'evidence_id': source['id'], 'evidence_quote': source['excerpt'], 'evidence_verified': True})
            position += 1
            cursor += duration + pause
    plan['unscheduled_count'] = max(0, run.get('metrics', {}).get('open', len(tasks)) - len(blocks))
    if not events:
        plan['coverage_note'] = '선택한 일정이 없습니다. 입력한 근무 시간만 기준으로 배치했으므로 실제 일정과 대조하세요.'
    return blocks, plan


def draft_eml(draft):
    message = EmailMessage(policy=policy.SMTP)
    message['Subject'] = draft['subject']
    if draft.get('recipient'):
        message['To'] = draft['recipient']
    message['X-Unsent'] = '1'
    message.set_content(draft['body'])
    return message.as_bytes()


def schedule_ics(run):
    def escape(text):
        return str(text).replace('\\', '\\\\').replace('\r', '').replace('\n', '\\n').replace(';', '\\;').replace(',', '\\,')
    def utc(value):
        return datetime.fromisoformat(value).astimezone(timezone.utc).strftime('%Y%m%dT%H%M%SZ')
    rows = ['BEGIN:VCALENDAR', 'VERSION:2.0', 'PRODID:-//Workmate//Focus Plan//KO', 'CALSCALE:GREGORIAN', 'METHOD:PUBLISH']
    for index, block in enumerate(run['result'].get('time_blocks', [])):
        identity = hashlib.sha256(f'{run["id"]}:{index}'.encode()).hexdigest()[:24]
        rows += ['BEGIN:VEVENT', 'UID:' + identity + '@workmate.local', 'DTSTAMP:' + utc(run['created_at']),
                 'DTSTART:' + utc(block['start']), 'DTEND:' + utc(block['end']),
                 'SUMMARY:' + escape(block['title']), 'DESCRIPTION:' + escape(block['reason']),
                 'STATUS:TENTATIVE', 'TRANSP:OPAQUE', 'END:VEVENT']
    rows.append('END:VCALENDAR')
    # RFC5545 folds on octet boundaries, without splitting UTF-8 characters.
    folded = []
    for row in rows:
        segment = ''
        for char in row:
            if len((segment + char).encode('utf-8')) > 73:
                folded.append(segment)
                segment = ' '
            segment += char
        folded.append(segment)
    return ('\r\n'.join(folded) + '\r\n').encode('utf-8')
